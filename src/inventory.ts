import type { Repo } from "./config.ts";
import { NAME, ORG } from "./github.ts";

export function renderInventory(repos: Repo[], ignored: Record<string, string>): string {
  const rows = [
    ...repos.map((repo) => [
      repo.name,
      repo.tier,
      repo.license,
      repo.maintainers.join(", "),
      repo.responseDays === null ? "best effort" : `${repo.responseDays} working days`,
      repo.archived ? "archived" : "active",
    ]),
    ...Object.entries(ignored).map(([name, reason]) => [name, "", "", "", "", `not managed: ${reason}`]),
  ].sort((a, b) => a[0]!.localeCompare(b[0]!));

  return [
    "# Repository inventory",
    "",
    `Generated by ${ORG}/${NAME} from \`repos/\` and \`ignored.yaml\`, do not edit.`,
    "",
    "| Repository | Tier | License | Maintainers | First response | State |",
    "| --- | --- | --- | --- | --- | --- |",
    ...rows.map(([name, ...cells]) => `| [${name}](https://github.com/${ORG}/${name}) | ${cells.join(" | ")} |`),
    "",
  ].join("\n");
}
